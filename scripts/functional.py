"""Tes fungsi di viewport HP (360x740) dan desktop. Jalankan dengan server lokal :8000."""
from playwright.sync_api import sync_playwright
ok=[];bad=[]
def chk(name,cond,info=''):
    (ok if cond else bad).append(name); print(('PASS ' if cond else 'FAIL ')+name+(' '+str(info) if info and not cond else ''))
with sync_playwright() as p:
    b=p.chromium.launch()
    c=b.new_context(viewport={'width':360,'height':740},device_scale_factor=2,has_touch=True,is_mobile=True)
    pg=c.new_page(); errs=[]
    pg.on('console',lambda m: errs.append(m.text) if m.type=='error' else None)
    pg.on('pageerror',lambda e: errs.append(str(e)))
    pg.goto('http://localhost:8000/',wait_until='networkidle'); pg.wait_for_timeout(1500)
    # dock
    chk('dock 5 item',pg.locator('#dock button').count()==5)
    r=pg.evaluate("()=>{const d=document.querySelector('#dock').getBoundingClientRect();return [d.left,d.right,innerWidth]}")
    chk('dock di dalam viewport',r[0]>=0 and r[1]<=r[2],r)
    for sid,label in [('projects','Projects'),('services','Services'),('team','Team'),('home','Home')]:
        pg.locator(f'#dock button[data-n="{sid}"]').tap(); pg.wait_for_timeout(1300)
        act=pg.evaluate("()=>document.querySelector('#dock [aria-current=true]')?.dataset.n")
        top=pg.evaluate(f"()=>Math.round(document.getElementById('{sid}').getBoundingClientRect().top)")
        chk(f'dock -> {sid} (active={act}, top={top})',act==sid and top<400)
    # More
    pg.locator('#more').tap(); pg.wait_for_timeout(500)
    chk('panel More terbuka',pg.evaluate("()=>document.querySelector('#sheet').classList.contains('open')"))
    n=pg.locator('#mg a').count(); chk('panel berisi 8 menu',n==8,n)
    bg=pg.evaluate("()=>getComputedStyle(document.querySelector('.sheet__pn')).backgroundColor")
    chk('latar panel solid',bg.startswith('rgb(') and 'rgba' not in bg,bg)
    pg.locator('#sheetX').tap(); pg.wait_for_timeout(500)
    chk('panel tutup via tombol close',pg.evaluate("()=>document.querySelector('#sheet').hidden"))
    for sid in ['about','skills','experience','showcase','updates','testimonials','faq','contact']:
        pg.locator('#more').tap(); pg.wait_for_timeout(400)
        pg.locator(f'#mg a[data-n="{sid}"]').tap(); pg.wait_for_timeout(1400)
        closed=pg.evaluate("()=>document.querySelector('#sheet').hidden")
        act=pg.evaluate("()=>document.querySelector('#dock #more').getAttribute('aria-current')")
        sec=pg.evaluate("()=>document.querySelector('#mg [aria-current=true]')?.dataset.n")
        top=pg.evaluate(f"()=>Math.round(document.getElementById('{sid}').getBoundingClientRect().top)")
        chk(f'More -> {sid} (closed={closed}, active={sec}, more={act}, top={top})',closed and sec==sid and act=='true' and top<500)
    # Escape + backdrop
    pg.locator('#more').tap(); pg.wait_for_timeout(400); pg.keyboard.press('Escape'); pg.wait_for_timeout(500)
    chk('Escape menutup panel',pg.evaluate("()=>document.querySelector('#sheet').hidden"))
    pg.locator('#more').tap(); pg.wait_for_timeout(400); pg.mouse.click(180,60); pg.wait_for_timeout(500)
    chk('klik backdrop menutup panel',pg.evaluate("()=>document.querySelector('#sheet').hidden"))
    # padding bawah / footer tidak tertutup
    pg.evaluate("scrollTo(0,document.body.scrollHeight)"); pg.wait_for_timeout(600)
    r=pg.evaluate("()=>{const f=document.querySelector('.foot__copy').getBoundingClientRect(),d=document.querySelector('#dock').getBoundingClientRect();return [Math.round(f.bottom),Math.round(d.top)]}")
    chk('footer tidak tertutup dock',r[0]<=r[1],r)
    # Projects: pencarian & filter
    pg.evaluate("document.getElementById('projects').scrollIntoView()"); pg.wait_for_timeout(500)
    pg.fill('#q','uploader'); pg.wait_for_timeout(200)
    chk('pencarian "uploader" -> 1 hasil',pg.locator('#pg .pcard').count()==1)
    pg.fill('#q','zzzz'); chk('pencarian kosong -> empty state',pg.locator('#pg .empty').count()==1)
    pg.locator('#pReset').tap(); pg.wait_for_timeout(200)
    chk('reset -> 4 project',pg.locator('#pg .pcard').count()==4)
    pg.locator('#pf [data-c="Web App"]').tap(); pg.wait_for_timeout(200)
    chk('filter Web App -> 2',pg.locator('#pg .pcard').count()==2)
    pg.locator('#pf [data-c="All"]').tap()
    pg.locator('#pg [data-d]').first.tap(); pg.wait_for_timeout(400)
    chk('dialog detail terbuka',pg.evaluate("()=>document.querySelector('#dlg').open"))
    pg.locator('#dx').tap(); pg.wait_for_timeout(300)
    chk('dialog detail tertutup',not pg.evaluate("()=>document.querySelector('#dlg').open"))
    # gambar nyata dimuat (scroll agar lazy load jalan)
    for y in range(0,12000,600): pg.evaluate(f"scrollTo(0,{y})"); pg.wait_for_timeout(60)
    pg.wait_for_timeout(800)
    chk('gambar AMP dimuat di kartu project',pg.evaluate("()=>[...document.querySelectorAll('#pg img')].some(i=>i.naturalWidth>0)"))
    # showcase lightbox
    pg.evaluate("document.getElementById('showcase').scrollIntoView()"); pg.wait_for_timeout(800)
    ready=pg.locator('#sh .shi.is-ready').count(); chk('showcase: 1 item siap (gambar nyata)',ready==1,ready)
    pg.locator('#sh .shi.is-ready').first.tap(); pg.wait_for_timeout(500)
    chk('lightbox terbuka',pg.evaluate("()=>document.querySelector('#lb').open"))
    pg.screenshot(path='/home/claude/shots/m-lightbox.png')
    pg.locator('#lbX').tap(); pg.wait_for_timeout(300)
    # FAQ
    pg.evaluate("document.getElementById('faq').scrollIntoView()"); pg.wait_for_timeout(500)
    s=pg.locator('#fq summary'); s.nth(0).tap(); pg.wait_for_timeout(300); s.nth(1).tap(); pg.wait_for_timeout(300)
    chk('FAQ hanya satu terbuka',pg.locator('#fq details[open]').count()==1)
    # form
    pg.evaluate("document.getElementById('contact').scrollIntoView()"); pg.wait_for_timeout(500)
    pg.locator('#fSend').tap(); pg.wait_for_timeout(300)
    chk('validasi menampilkan 3 error',all(pg.locator(f'#e-{k}').inner_text().strip() for k in 'nem'))
    pg.fill('#n','Budi'); pg.fill('#e','budi@contoh.com'); pg.fill('#m','Halo, saya ingin membuat website toko.')
    pg.locator('#fSend').tap(); pg.wait_for_timeout(300)
    st=pg.locator('#status').inner_text()
    chk('form valid tanpa kanal -> TIDAK mengklaim terkirim','belum terkirim' in st.lower() and 'berhasil' not in st.lower(),st)
    pg.locator('#n').focus(); pg.wait_for_timeout(300)
    chk('dock disembunyikan saat mengetik',pg.evaluate("()=>document.documentElement.classList.contains('typing')"))
    pg.screenshot(path='/home/claude/shots/m-contact.png')
    chk('tanpa error console',not errs,errs)
    c.close()
    # reduced motion
    c=b.new_context(viewport={'width':360,'height':740},reduced_motion='reduce'); pg=c.new_page(); pg.goto('http://localhost:8000/',wait_until='networkidle')
    chk('reduced-motion: tidak ada animasi berjalan',pg.evaluate("()=>document.getAnimations().filter(a=>a.playState==='running'&&a.effect.getComputedTiming().iterations===Infinity).length===0"))
    c.close()
    b.close()
print(f'\n{len(ok)} lulus, {len(bad)} gagal')
